    /**
     * @param list<int> $fields
     */
    #[DataProvider('parseCases')]
    public function testParses(string $input, string $format, array $fields, string $rest): void
    {
        $parsed = Strptime::parse($input, $format, ZoneInfo::utc());

        self::assertNotNull($parsed, $format . self::SEPARATOR . $input);
        self::assertSame($fields, $parsed[0], $format . self::SEPARATOR . $input);
        self::assertSame($rest, $parsed[1], $format . self::SEPARATOR . $input);
    }

