    #[DataProvider('rejectCases')]
    public function testRejects(string $input, string $format): void
    {
        self::assertNull(Strptime::parse($input, $format, ZoneInfo::utc()), $format . self::SEPARATOR . $input);
    }

    /**
     * @return iterable<string, array{string, string}>
     */
    public static function rejectCases(): iterable
    {
        $groups = [
            '%d%%'    => ['5x', '5'],
            '%j'      => ['000', '367'],
            '%u'      => ['0', '8'],
            '%w'      => ['7'],
            '%U'      => ['54'],
            '%W'      => ['54'],
            '%I'      => ['13', '00'],
            '%I %p'   => ['10 xx'],
            '%I %p%Y' => ['10 PMx'],
            '%s'      => [' x', 'x', ''],
            '%s %b'   => [self::EPOCH . ' 2020'],
            '%b'      => ['xyz', ''],
            '%a'      => ['Foo'],
            '%z'      => ['x0100', '+0160', '+0198', '+1', '+123', '+01:3 x', '+01:30:'],
            '%Q'      => ['xx', '5'],
            '%C %Y'   => ['20'],
            '%C'      => ['2015-03-05'],
        ];

        $ranges = [
            '%M'    => ['60'],
            '%S'    => ['62'],
            '%H'    => ['24'],
            '%d'    => ['00', '32'],
            '%m'    => ['00', '13'],
            '%Q'    => ['', ' x'],
            '%p'    => ['', ' x'],
            '%z'    => ['', '+01:3'],
            '%g '   => ['123 '],
            '%g%d'  => ['12345'],
        ];

        foreach (self::mergedInputs($groups, $ranges) as $format => $inputs) {
            foreach ($inputs as $input) {
                yield $format . self::SEPARATOR . $input => [$input, $format];
            }
        }
    }

    /**
     * @param array<string, list<array{string, list<int>, string}>> ...$sets
     *
     * @return array<string, list<array{string, list<int>, string}>>
     */
    private static function merged(array ...$sets): array
    {
        $merged = [];
        foreach ($sets as $set) {
            foreach ($set as $format => $cases) {
                $merged[$format] = array_merge($merged[$format] ?? [], $cases);
            }
        }

        return $merged;
    }

    /**
     * @param array<string, list<string>> ...$sets
     *
     * @return array<string, list<string>>
     */
    private static function mergedInputs(array ...$sets): array
    {
        $merged = [];
        foreach ($sets as $set) {
            foreach ($set as $format => $inputs) {
                $merged[$format] = array_merge($merged[$format] ?? [], $inputs);
            }
        }

        return $merged;
    }
